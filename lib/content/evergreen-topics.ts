/** The evergreen publishing queue.
 *
 * These replace the daily market recaps. The difference that matters for search: a recap answers
 * "what happened on 6 September", a query nobody types and that is worthless a day later, while
 * each of these answers a question that is typed every month and stays answerable for years.
 *
 * `targetQuery` is the single search phrase the piece is written for — it belongs in the H1, the
 * first paragraph and the meta description, and nowhere else artificially.
 *
 * Every entry here has a measured `shows` figure, read off wordstat.yandex.ru for region 225
 * (Russia) on 2026-09-07 for the preceding month, and the queue is ordered by it. Do not add a
 * topic without measuring it first, and read the breakdown rather than the headline number — the
 * first draft of this list was built on plausible-sounding phrasings and most of them turned out
 * to be empty. What got thrown out, and why:
 *
 *   налог с дивидендов американских акций  8    nobody phrases it that way
 *   спотовый ETF на биткоин                3    "
 *   комиссия за газ в Ethereum             2    "
 *   что такое халвинг биткоина            13    "
 *   usdt или usdc                         56    too thin to be worth a page
 *   памп криптовалюты                     84    "
 *   сплит акций                        2 611    almost entirely air-conditioner shoppers
 *   ликвидация позиции                   518    industrial-safety and generic intent; the
 *                                               crypto reading of it is 5 shows
 */
export interface EvergreenTopic {
  /** Stable URL slug — never change one after publication. */
  slug: string;
  /** The exact query this article is meant to rank for. */
  targetQuery: string;
  /** Wordstat shows per month, region 225, measured 2026-09-07. */
  shows: number;
  /** Working headline. The model may refine the wording but must keep the query intact. */
  workingTitle: string;
  /** What the piece has to cover to actually answer the query rather than circle it. */
  brief: string;
  /** Tickers/assets to link out to, if the topic naturally involves any. */
  relatedTickers?: string[];
}

