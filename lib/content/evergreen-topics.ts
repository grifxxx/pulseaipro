/** The evergreen publishing queue.
 *
 * These replace the daily market recaps. The difference that matters for search: a recap answers
 * "what happened on 6 September", a query nobody types and that is worthless a day later, while
 * each of these answers a question that is typed every month and stays answerable for years.
 *
 * `targetQuery` is the single search phrase the piece is written for — it belongs in the H1, the
 * first paragraph and the meta description, and nowhere else artificially.
 *
 * Every `shows` figure below was read off wordstat.yandex.ru for region 225 (Russia) on
 * 2026-09-07, for the preceding month. The queue is ordered by that number. Re-check before
 * adding new topics — the first draft of this list was built on plausible-sounding phrasings and
 * most of them turned out to have no demand at all ("налог с дивидендов американских акций" — 8
 * shows, "что такое халвинг биткоина" — 13, "спотовый ETF на биткоин" — 3). Check the breakdown,
 * not just the headline number: "сплит акций" looks like 2 611 shows until you see that nearly
 * all of it is people shopping for air conditioners. */
export interface EvergreenTopic {
  /** Stable URL slug — never change one after publication. */
  slug: string;
  /** The exact query this article is meant to rank for. */
  targetQuery: string;
  /** Wordstat shows per month, region 225, measured 2026-09-07. Null = not yet verified. */
  shows: number | null;
  /** Working headline. The model may refine the wording but must keep the query intact. */
  workingTitle: string;
  /** What the piece has to cover to actually answer the query rather than circle it. */
  brief: string;
  /** Tickers/assets to link out to, if the topic naturally involves any. */
  relatedTickers?: string[];
}

